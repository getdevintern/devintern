/**
 * Operate an installed worker service and tell the truth about it.
 *
 * `service.ts` renders and installs the systemd unit / launchd agent. This
 * module starts, stops, restarts, uninstalls, and inspects it, and answers
 * the question the old wizard got wrong: did the worker actually come up?
 * `waitForWorkerStart` watches the worker's own lifecycle record and lock
 * (and the unit's state on Linux) instead of trusting `is-active`, which says
 * "active" for a worker that exits a second later.
 *
 * Every effect goes through the injectable {@link WorkerServiceDeps}.
 */

import { join } from "path";
import { resolveWorkerStatus } from "../observability/dashboard-api";
import type { WorkerStatusView } from "../observability/dashboard-api";
import { readWorkerLogs } from "../observability/worker-logs";
import { readWorkerLifecycle, summarizeStartupFailure } from "./lifecycle";
import type { WorkerLifecycleRecord } from "./lifecycle";
import {
  LAUNCHD_LABEL,
  LAUNCHD_LOG_NAME,
  SERVICE_MANAGED_MARKER,
  SYSTEMD_UNIT_NAME,
  checkServiceManager,
  commandDetail,
  installWorkerService,
  launchdAgentPath,
  resolveServiceDeps,
  systemdUnitPath,
} from "./service";
import type {
  ResolvedServiceDeps,
  RunCommandResult,
  ServiceInstallResult,
  WorkerServiceDeps,
} from "./service";
import type { MemoryBudgetPercentages } from "./memory-budget";

const UNIT = "devintern-worker";

/**
 * One-word service state:
 * - `running`: the service is up and the worker finished starting.
 * - `starting`: the service is up but the worker has not finished starting.
 * - `restarting`: the worker exited and the service manager will retry it.
 * - `failed`: the service gave up (or the worker exited with a permanent error).
 * - `stopped`: installed but not running.
 * - `not_installed`, `unavailable`: no service here / no service manager.
 */
export type ServiceRunState =
  | "running"
  | "starting"
  | "restarting"
  | "failed"
  | "stopped"
  | "not_installed"
  | "unavailable";

/** What the service manager says about the unit (fields it reported). */
export interface ServiceManagerView {
  activeState?: string;
  subState?: string;
  result?: string;
  execMainStatus?: number;
  restarts?: number;
  mainPid?: number;
  /** launchd: whether the label is loaded in the gui domain. */
  loaded?: boolean;
  /** launchd: `last exit code` from `launchctl print`. */
  lastExitCode?: number;
}

export interface WorkerServiceStatus {
  platform: NodeJS.Platform;
  state: ServiceRunState;
  /** Why the service is unavailable or what went wrong. */
  reason?: string;
  installed: boolean;
  /** Generated by DevIntern (safe to update or uninstall). */
  managed: boolean;
  /** Starts at boot/login (systemd `is-enabled`; launchd: installed). */
  enabled: boolean;
  definitionPath: string | null;
  manager: ServiceManagerView;
  worker: WorkerStatusView;
  lastExit: WorkerLifecycleRecord | null;
}

/** Outcome of the honest start check. */
export type StartCheck =
  | { state: "running"; pid?: number }
  | { state: "failed"; reason: string; permanent: boolean; logLines: string[] }
  | { state: "starting"; waitedMs: number };

export interface ServiceActionResult {
  ok: boolean;
  error?: string;
  /** The action did nothing because the service was already in that state. */
  unchanged?: boolean;
}

/** Path of the installed definition on this platform, or null. */
function definitionPathFor(d: ResolvedServiceDeps): string | null {
  if (d.platform === "linux") return systemdUnitPath(d.homedir);
  if (d.platform === "darwin") return launchdAgentPath(d.homedir);
  return null;
}

function launchdTarget(d: ResolvedServiceDeps): string | null {
  return d.uid === undefined ? null : `gui/${d.uid}/${LAUNCHD_LABEL}`;
}

/** Parse `systemctl show` `Key=Value` lines. */
export function parseSystemdShow(stdout: string): ServiceManagerView {
  const values = new Map<string, string>();
  for (const line of stdout.split("\n")) {
    const eq = line.indexOf("=");
    if (eq > 0) values.set(line.slice(0, eq).trim(), line.slice(eq + 1).trim());
  }
  const int = (key: string): number | undefined => {
    const raw = values.get(key);
    if (raw === undefined || raw === "" || !/^-?\d+$/.test(raw)) return undefined;
    return Number(raw);
  };
  return {
    ...(values.get("ActiveState") ? { activeState: values.get("ActiveState") } : {}),
    ...(values.get("SubState") ? { subState: values.get("SubState") } : {}),
    ...(values.get("Result") ? { result: values.get("Result") } : {}),
    ...(int("ExecMainStatus") !== undefined ? { execMainStatus: int("ExecMainStatus") } : {}),
    ...(int("NRestarts") !== undefined ? { restarts: int("NRestarts") } : {}),
    ...(int("MainPID") ? { mainPid: int("MainPID") } : {}),
  };
}

/** Parse the parts of `launchctl print` output the status needs. */
export function parseLaunchctlPrint(stdout: string): ServiceManagerView {
  const state = /^\s*state\s*=\s*(\S+)/m.exec(stdout)?.[1];
  const pid = /^\s*pid\s*=\s*(\d+)/m.exec(stdout)?.[1];
  const lastExit = /^\s*last exit code\s*=\s*(-?\d+)/m.exec(stdout)?.[1];
  return {
    loaded: true,
    ...(state ? { activeState: state } : {}),
    ...(pid ? { mainPid: Number(pid) } : {}),
    ...(lastExit !== undefined ? { lastExitCode: Number(lastExit) } : {}),
  };
}

async function systemdView(d: ResolvedServiceDeps): Promise<ServiceManagerView> {
  const result = await d.run("systemctl", [
    "--user",
    "show",
    UNIT,
    "--property=ActiveState,SubState,Result,ExecMainStatus,NRestarts,MainPID",
  ]);
  return result.status === 0 ? parseSystemdShow(result.stdout) : {};
}

async function launchdView(d: ResolvedServiceDeps): Promise<ServiceManagerView> {
  const target = launchdTarget(d);
  if (!target) return {};
  const result = await d.run("launchctl", ["print", target]);
  return result.status === 0 ? parseLaunchctlPrint(result.stdout) : { loaded: false };
}

async function managerView(d: ResolvedServiceDeps): Promise<ServiceManagerView> {
  if (d.platform === "linux") return systemdView(d);
  if (d.platform === "darwin") return launchdView(d);
  return {};
}

/** Map the service manager's view plus the worker's own record to one state. */
export function deriveRunState(
  platform: NodeJS.Platform,
  manager: ServiceManagerView,
  worker: WorkerStatusView,
  lastExit: WorkerLifecycleRecord | null,
): ServiceRunState {
  const workerUp = worker.status === "running";
  if (platform === "linux") {
    const { activeState, subState } = manager;
    if (activeState === "active") return workerUp ? "running" : "starting";
    if (activeState === "activating")
      return subState === "auto-restart" ? "restarting" : "starting";
    if (activeState === "failed") return "failed";
    if (activeState === "deactivating") return "stopped";
    return lastExit?.state === "startup_failed" && lastExit.permanent ? "failed" : "stopped";
  }
  if (!manager.loaded) return "stopped";
  if (manager.activeState === "running") return workerUp ? "running" : "starting";
  if (lastExit?.state === "startup_failed") return lastExit.permanent ? "failed" : "restarting";
  return manager.lastExitCode !== undefined && manager.lastExitCode !== 0
    ? "restarting"
    : "stopped";
}

/**
 * Inspect the installed service and the worker it runs. Read-only.
 *
 * @param workspaceDir - Workspace home (worker lock and lifecycle record)
 * @param deps - Injectable platform, file system, and command runner
 */
export async function queryWorkerService(
  workspaceDir: string,
  deps: WorkerServiceDeps = {},
): Promise<WorkerServiceStatus> {
  const d = resolveServiceDeps(deps);
  const definitionPath = definitionPathFor(d);
  const worker = resolveWorkerStatus(workspaceDir);
  const lastExit = readWorkerLifecycle(workspaceDir);
  const base = {
    platform: d.platform,
    definitionPath,
    worker,
    lastExit,
    manager: {},
    installed: false,
    managed: false,
    enabled: false,
  };
  const availability = await checkServiceManager(deps);
  if (!availability.available) {
    return { ...base, state: "unavailable", reason: availability.reason };
  }
  const installed = definitionPath !== null && d.exists(definitionPath);
  if (!installed || definitionPath === null) return { ...base, state: "not_installed" };
  let managed = false;
  try {
    managed = d.readFile(definitionPath).includes(SERVICE_MANAGED_MARKER);
  } catch {
    managed = false;
  }
  const enabled =
    d.platform === "linux"
      ? (await d.run("systemctl", ["--user", "is-enabled", UNIT])).status === 0
      : true;
  const manager = await managerView(d);
  return {
    ...base,
    installed,
    managed,
    enabled,
    manager,
    state: deriveRunState(d.platform, manager, worker, lastExit),
  };
}

function failure(prefix: string, result: RunCommandResult): ServiceActionResult {
  return { ok: false, error: `${prefix} failed: ${commandDetail(result)}` };
}

/** `ok: false` unless a service definition is installed here. */
function requireInstalled(d: ResolvedServiceDeps): ServiceActionResult | null {
  const path = definitionPathFor(d);
  if (path === null) return { ok: false, error: `no service definition exists for ${d.platform}` };
  if (!d.exists(path)) {
    return {
      ok: false,
      error: "the worker service is not installed; run `devintern worker service install`",
    };
  }
  return null;
}

async function bootstrapLaunchd(d: ResolvedServiceDeps): Promise<ServiceActionResult> {
  if (d.uid === undefined) return { ok: false, error: "could not determine your user id" };
  const plist = launchdAgentPath(d.homedir);
  const result = await d.run("launchctl", ["bootstrap", `gui/${d.uid}`, plist]);
  return result.status === 0 ? { ok: true } : failure("launchctl bootstrap", result);
}

/** Start the installed service (idempotent: a running service is left alone). */
export async function startWorkerService(
  deps: WorkerServiceDeps = {},
): Promise<ServiceActionResult> {
  const d = resolveServiceDeps(deps);
  const missing = requireInstalled(d);
  if (missing) return missing;
  if (d.platform === "linux") {
    // Clears a `failed` state (and its start-rate limit) left by a permanent error.
    await d.run("systemctl", ["--user", "reset-failed", UNIT]);
    const result = await d.run("systemctl", ["--user", "start", UNIT]);
    return result.status === 0 ? { ok: true } : failure("systemctl --user start", result);
  }
  const view = await launchdView(d);
  if (!view.loaded) return bootstrapLaunchd(d);
  if (view.activeState === "running") return { ok: true, unchanged: true };
  const target = launchdTarget(d) as string;
  const result = await d.run("launchctl", ["kickstart", target]);
  return result.status === 0 ? { ok: true } : failure("launchctl kickstart", result);
}

/**
 * Stop the service and wait for the worker's graceful shutdown. On macOS the
 * agent is unloaded (`bootout`), because KeepAlive would restart a killed
 * worker; `start` loads it again. Idempotent.
 */
export async function stopWorkerService(
  deps: WorkerServiceDeps = {},
): Promise<ServiceActionResult> {
  const d = resolveServiceDeps(deps);
  const path = definitionPathFor(d);
  if (path !== null && !d.exists(path)) return { ok: true, unchanged: true };
  const missing = requireInstalled(d);
  if (missing) return missing;
  if (d.platform === "linux") {
    const result = await d.run("systemctl", ["--user", "stop", UNIT]);
    return result.status === 0 ? { ok: true } : failure("systemctl --user stop", result);
  }
  const view = await launchdView(d);
  if (!view.loaded) return { ok: true, unchanged: true };
  const result = await d.run("launchctl", ["bootout", launchdTarget(d) as string]);
  return result.status === 0 ? { ok: true } : failure("launchctl bootout", result);
}

/** Restart the service (starts it when stopped or failed). */
export async function restartWorkerService(
  deps: WorkerServiceDeps = {},
): Promise<ServiceActionResult> {
  const d = resolveServiceDeps(deps);
  const missing = requireInstalled(d);
  if (missing) return missing;
  if (d.platform === "linux") {
    await d.run("systemctl", ["--user", "reset-failed", UNIT]);
    const result = await d.run("systemctl", ["--user", "restart", UNIT]);
    return result.status === 0 ? { ok: true } : failure("systemctl --user restart", result);
  }
  const view = await launchdView(d);
  if (!view.loaded) return bootstrapLaunchd(d);
  const result = await d.run("launchctl", ["kickstart", "-k", launchdTarget(d) as string]);
  return result.status === 0 ? { ok: true } : failure("launchctl kickstart -k", result);
}

/**
 * Stop, disable, and remove a DevIntern-managed service definition.
 * A hand-written definition is refused; an absent one is a no-op.
 */
export async function uninstallWorkerService(
  deps: WorkerServiceDeps = {},
): Promise<ServiceActionResult> {
  const d = resolveServiceDeps(deps);
  const path = definitionPathFor(d);
  if (path === null) return { ok: false, error: `no service definition exists for ${d.platform}` };
  if (!d.exists(path)) return { ok: true, unchanged: true };
  if (!d.readFile(path).includes(SERVICE_MANAGED_MARKER)) {
    return {
      ok: false,
      error: `${path} is a custom service definition; remove it yourself`,
    };
  }
  if (d.platform === "linux") {
    const disable = await d.run("systemctl", ["--user", "disable", "--now", UNIT]);
    if (disable.status !== 0) return failure("systemctl --user disable --now", disable);
    d.remove(path);
    await d.run("systemctl", ["--user", "daemon-reload"]);
    await d.run("systemctl", ["--user", "reset-failed", UNIT]);
    return { ok: true };
  }
  const target = launchdTarget(d);
  if (target && (await launchdView(d)).loaded) {
    const bootout = await d.run("launchctl", ["bootout", target]);
    if (bootout.status !== 0) return failure("launchctl bootout", bootout);
  }
  d.remove(path);
  return { ok: true };
}

/** Install (or update) the service, then wait for the worker to finish starting. */
export async function installAndStartWorkerService(
  options: {
    workspaceDir: string;
    execPath: string;
    runtimePath?: string;
    environmentPath?: string;
    /** Host-memory percentages written into the systemd unit (Linux only). */
    memory?: MemoryBudgetPercentages;
    /** 0 skips the start check. */
    waitMs?: number;
    now?: () => number;
    /** Override the start check (tests). */
    waitForStart?: (since: number) => Promise<StartCheck>;
  },
  deps: WorkerServiceDeps = {},
): Promise<{ install: ServiceInstallResult; start?: StartCheck }> {
  const since = (options.now ?? Date.now)();
  const install = await installWorkerService(
    {
      workspaceDir: options.workspaceDir,
      execPath: options.execPath,
      runtimePath: options.runtimePath,
      environmentPath: options.environmentPath,
      ...(options.memory ? { memory: options.memory } : {}),
    },
    deps,
  );
  if (!install.ok || options.waitMs === 0) return { install };
  const start = options.waitForStart
    ? await options.waitForStart(since)
    : await waitForWorkerStart(
        { workspaceDir: options.workspaceDir, since, timeoutMs: options.waitMs },
        deps,
      );
  return { install, start };
}

/** Where the service manager keeps the worker's raw output. */
export function serviceLogCommand(platform: NodeJS.Platform, workspaceDir: string): string {
  return platform === "darwin"
    ? `tail -n 100 ${join(workspaceDir, LAUNCHD_LOG_NAME)}`
    : `journalctl --user -u ${SYSTEMD_UNIT_NAME} -n 100 --no-pager`;
}

/** Error lines the worker logged at or after `since` (epoch ms), newest last. */
export function startupErrorLines(workspaceDir: string, since: number, max = 10): string[] {
  try {
    const { entries } = readWorkerLogs({ dirs: [workspaceDir], limit: 200 });
    return entries
      .filter((entry) => entry.stream === "err" && (entry.timestamp ?? 0) >= since)
      .map((entry) => entry.message)
      .filter((message) => message.trim().length > 0)
      .slice(-max);
  } catch {
    return [];
  }
}

export interface WaitForStartOptions {
  workspaceDir: string;
  /** Epoch ms when the start was requested; older records are ignored. */
  since: number;
  /** How long to wait for the worker to finish starting. */
  timeoutMs?: number;
  intervalMs?: number;
  now?: () => number;
  sleep?: (ms: number) => Promise<void>;
}

/** Default wait for a worker to finish starting (orphan recovery, probes, sources). */
export const DEFAULT_START_TIMEOUT_MS = 45_000;

/**
 * Wait until the worker started by the service finishes starting, fails, or
 * the timeout passes.
 *
 * `running` needs the worker's own `started` record from this start and a
 * live worker lock. `failed` is a `startup_failed` record from this start, a
 * unit that systemd marked failed, or one waiting to restart after an exit.
 */
export async function waitForWorkerStart(
  options: WaitForStartOptions,
  deps: WorkerServiceDeps = {},
): Promise<StartCheck> {
  const d = resolveServiceDeps(deps);
  const timeoutMs = options.timeoutMs ?? DEFAULT_START_TIMEOUT_MS;
  const intervalMs = options.intervalMs ?? 500;
  const now = options.now ?? Date.now;
  const sleep = options.sleep ?? ((ms: number) => Bun.sleep(ms));
  const started = now();
  // Same host, same clock: a record older than the request belongs to the
  // previous worker (for example its `started` record during a restart).
  const { since } = options;
  const failedWith = (fallback: string, permanent: boolean, record?: WorkerLifecycleRecord) => {
    const logLines = startupErrorLines(options.workspaceDir, since);
    const reason = summarizeStartupFailure(record?.message) ?? fallback;
    return {
      state: "failed" as const,
      reason,
      permanent,
      logLines: logLines.length > 0 ? logLines : (record?.message?.split("\n") ?? []),
    };
  };
  for (;;) {
    const record = readWorkerLifecycle(options.workspaceDir);
    const fresh = record !== null && Date.parse(record.at) >= since;
    if (fresh && record.state === "startup_failed") {
      return failedWith("the worker exited while starting", record.permanent === true, record);
    }
    if (fresh && record.state === "started") {
      const worker = resolveWorkerStatus(options.workspaceDir);
      if (worker.status === "running") return { state: "running", pid: worker.pid };
    }
    if (d.platform === "linux") {
      const view = await systemdView(d);
      if (view.activeState === "failed") {
        return failedWith(
          `the service failed (${view.result ?? "unknown result"}, exit status ${view.execMainStatus ?? "?"})`,
          true,
          fresh ? record : undefined,
        );
      }
      if (view.activeState === "activating" && view.subState === "auto-restart") {
        return failedWith(
          `the worker exited with status ${view.execMainStatus ?? "?"}; systemd will retry it`,
          false,
          fresh ? record : undefined,
        );
      }
    }
    const waited = now() - started;
    if (waited >= timeoutMs) return { state: "starting", waitedMs: waited };
    await sleep(intervalMs);
  }
}
