import { expect, test } from "bun:test";
import { resolveGitLabConfig } from "../../helpers/gitlab-config";
import { GitLab } from "../../providers/gitlab";

const forbiddenRead = (): never => {
  throw new Error("Local credentials must not be read");
};

test("GitLab CI requires explicit credentials without reading local files", () => {
  expect(() => resolveGitLabConfig({ CI: "true" }, forbiddenRead)).toThrow("CI requires");
  expect(() =>
    resolveGitLabConfig({ E2E_GITLAB_URL: "http://localhost:8929" }, forbiddenRead),
  ).toThrow("Set both");
  expect(
    resolveGitLabConfig(
      { CI: "true", E2E_GITLAB_URL: "http://localhost:8929/", E2E_GITLAB_TOKEN: "test-token" },
      forbiddenRead,
    ),
  ).toEqual({ baseUrl: "http://localhost:8929", token: "test-token" });
});

test("local GitLab credentials come from the generated file", () => {
  expect(
    resolveGitLabConfig({}, () => ({ baseUrl: "http://127.0.0.1:8929", token: "local-token" })),
  ).toEqual({ baseUrl: "http://127.0.0.1:8929", token: "local-token" });
});

test("GitLab rejects credential-bearing URLs and non-HTTP protocols", () => {
  expect(() => new GitLab("http://user:password@localhost", "test-token")).toThrow(
    "without credentials",
  );
  expect(() => new GitLab("file:///tmp/gitlab", "test-token")).toThrow("HTTP(S)");
});

test("project cleanup refuses project names that are not generated by the suite", async () => {
  const gitlab = new GitLab("http://localhost:8929", "test-token");
  await expect(
    gitlab.deleteProject({
      id: 1,
      path_with_namespace: "root/production",
      http_url_to_repo: "http://localhost:8929/root/production.git",
    }),
  ).rejects.toThrow("Refusing to delete");
});
